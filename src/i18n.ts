const initialLang = (() => {
  try {
    const saved = localStorage.getItem('foodcovering_language') || localStorage.getItem('i18nextLng');
    if (saved && ['en', 'ta', 'hi', 'te', 'kn', 'ml', 'es', 'fr'].includes(saved.split('-')[0])) {
      return saved.split('-')[0];
    }
  } catch (e) {
    // ignore
  }
  return 'en';
})();

i18n
  .use(LanguageDetector)
  .use(initReactI18next)
  .init({
    resources,
    lng: initialLang,
    fallbackLng: 'en',
    interpolation: {
      escapeValue: false, // react already escapes
    },
    detection: {
      order: ['localStorage', 'navigator'],
      lookupLocalStorage: 'foodcovering_language',
      caches: ['localStorage'],
    }
  });

export default i18n;
