/**
 * Translates a single text string into target language if dictionary match exists
 */
export function translateText(text: string, lang: SupportedLanguage): string {
  if (!text || lang === 'en') return text;
  const trimmed = text.trim();
  if (!trimmed) return text;

  const langDict = DICTIONARY[lang];
  if (!langDict) return text;

  // Direct exact match
  if (langDict[trimmed]) {
    const translated = langDict[trimmed];
    const leading = text.match(/^\s*/)?.[0] || '';
    const trailing = text.match(/\s*$/)?.[0] || '';
    return leading + translated + trailing;
  }

  // Case-insensitive match
  const lowerTrimmed = trimmed.toLowerCase();
  for (const [key, val] of Object.entries(langDict)) {
    if (key.toLowerCase() === lowerTrimmed) {
      const leading = text.match(/^\s*/)?.[0] || '';
      const trailing = text.match(/\s*$/)?.[0] || '';
      return leading + val + trailing;
    }
  }

  return text;
}
